import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { ENGINE_FILE, bundleEngine } from "./bundle";

let dir: string;
let fresh: string;
let inputs: string[];

beforeAll(async () => {
  dir = mkdtempSync(path.join(tmpdir(), "report-engine-"));
  const outfile = path.join(dir, "report-engine.js");
  inputs = (await bundleEngine(outfile)).inputs;
  fresh = readFileSync(outfile, "utf8");
});

afterAll(() => rmSync(dir, { recursive: true, force: true }));

describe("the report engine bundle", () => {
  it("the committed bundle is current", () => {
    // Run `npm run engine:bundle` after changing the report builder.
    expect(fresh === readFileSync(ENGINE_FILE, "utf8")).toBe(true);
  });

  it("starts with the generated banner and the Deno types", () => {
    expect(fresh.split("\n").slice(0, 2)).toEqual([
      "// generated by npm run engine:bundle; do not edit",
      '// @ts-self-types="./report-engine.d.ts"',
    ]);
  });

  it("embeds no checked-in data, components or pages", () => {
    expect(
      inputs.filter((file) => /^src\/(components|app|data)\//.test(file)),
    ).toEqual([]);
    expect(inputs.filter((file) => file.endsWith(".json"))).toEqual([]);
    expect(fresh).not.toContain("Aquaculture Farmer");
    expect(fresh).not.toContain("skillselect-2026-10-31");
  });

  it("reads the manifest and index through the live holders", () => {
    expect(inputs).toContain("src/lib/report-issue/live-json.ts");
    expect(fresh).not.toMatch(/from\s+"@\//);
  });
});
